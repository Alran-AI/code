/**
 * Spec-test authoring (spec 13.2, ULT-13).
 *
 * The freeze in `spec-tests.ts` only means something if the frozen checks exist
 * before the first worker starts. This module is the authoring step: it turns the
 * goal document's criteria into test files, and it writes them into the run
 * directory first rather than straight into the repository.
 *
 * Two deliberate choices:
 *
 *   - **The agent writes, the harness places.** The model produces file contents;
 *     this module decides where they go and refuses anything outside the frozen
 *     directory, so a reply cannot smuggle the checks somewhere a worker could
 *     edit, or somewhere no runner would pick up.
 *   - **A spec test must be able to fail.** The prompt says so explicitly: a
 *     check that passes before the feature exists is not an acceptance check, it
 *     is a tautology, and a run could satisfy it by doing nothing.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import type { Criterion, GoalDocument } from './goal.js';
import { SPEC_TEST_DIR } from './spec-tests.js';

/** The file-naming convention; kept here so the prompt and the writer agree. */
export const SPEC_TEST_FILENAME = '.spec.ts';

/** The file a criterion's spec test belongs in. */
export function specTestFileFor(
  criterionId: string,
  specTestDir: string = SPEC_TEST_DIR,
): string {
  const slug = criterionId.trim().replace(/[^A-Za-z0-9_-]+/gu, '-').toLowerCase() || 'criterion';
  return `${specTestDir}/${slug}${SPEC_TEST_FILENAME}`;
}

export interface SpecTestFile {
  readonly file: string;
  readonly content: string;
}

/** One rendered file, before it is written anywhere. */
export function renderSpecTest(
  criterion: Criterion,
  options: { readonly specTestDir?: string } = {},
): SpecTestFile {
  const specTestDir = options.specTestDir ?? SPEC_TEST_DIR;
  const content = [
    `// GENERATED by Ultra from criterion ${criterion.id}. Do not edit by hand.`,
    `// Priority: ${criterion.priority} · verification: ${criterion.verification}`,
    `//`,
    `// ${criterion.description}`,
    `//`,
    `// This test must FAIL until the criterion is actually implemented. If it passes`,
    `// before the work exists, it is not an acceptance check.`,
    ``,
    `export const criterion = ${JSON.stringify(criterion.id)};`,
    `export const description = ${JSON.stringify(criterion.description)};`,
    `export const priority = ${JSON.stringify(criterion.priority)};`,
    `export const verification = ${JSON.stringify(criterion.verification)};`,
    ``,
  ].join('\n');
  return { file: specTestFileFor(criterion.id, specTestDir), content };
}

/** The prompt for the spec-test agent. */
export function buildSpecTestPrompt(input: {
  readonly goal: GoalDocument;
  readonly specTestDir?: string;
  /** Commands the project uses to run tests, so the checks are runnable. */
  readonly testCommands?: readonly string[];
}): string {
  const specTestDir = input.specTestDir ?? SPEC_TEST_DIR;
  const criteria = input.goal.criteria
    .map(
      (criterion) =>
        `- ${criterion.id} (${criterion.priority}, verify by ${criterion.verification}): ${criterion.description}`,
    )
    .join('\n');

  return [
    'Turn these acceptance criteria into executable spec tests.',
    '',
    'Goal:',
    input.goal.goal,
    '',
    'Criteria:',
    criteria,
    '',
    `Write every file into \`${specTestDir}/\`.`,
    ...(input.testCommands && input.testCommands.length > 0
      ? [`The project runs tests with: ${input.testCommands.join(', ')}.`]
      : []),
    '',
    'Rules:',
    '- One file per criterion, so a failure names the criterion that failed.',
    '- Each test must FAIL until the criterion is implemented. A test that passes',
    '  before the work exists is a tautology and will be rejected.',
    '- Assert real behaviour: call the CLI, drive the API, inspect the result.',
    '  Do not assert on your own mocks.',
    '- These files are read-only once written. No worker may edit them, and you',
    '  must not write them anywhere else.',
    '',
    'Reply with one block per file, exactly in this form:',
    '',
    '```file tests/spec/<name>.spec.ts',
    '<file contents>',
    '```',
  ].join('\n');
}

/**
 * Parses the agent's reply into files.
 *
 * Fails closed twice: a file outside the frozen directory is rejected, and a
 * reply with no files at all is rejected, because an empty authoring step would
 * leave the run with no acceptance checks while looking successful.
 */
export function parseSpecTestReply(
  text: string,
  specTestDir: string = SPEC_TEST_DIR,
): SpecTestFile[] {
  const files: SpecTestFile[] = [];
  const block = /```file\s+(\S+?)\s*\n([\s\S]*?)```/gu;
  let match: RegExpExecArray | null;
  while ((match = block.exec(text)) !== null) {
    const file = match[1]!.trim().replace(/\\/gu, '/').replace(/^\.\//u, '');
    const content = match[2]!;
    if (!isInside(file, specTestDir)) {
      throw new Error(
        `the spec-test agent wrote ${file}, which is outside ${specTestDir}/; the spec tests must live in the frozen directory`,
      );
    }
    files.push({ file, content: content.endsWith('\n') ? content : `${content}\n` });
  }
  if (files.length === 0) {
    throw new Error('the spec-test agent produced no files');
  }
  return files;
}

function isInside(file: string, specTestDir: string): boolean {
  const prefix = `${specTestDir.replace(/\/+$/u, '')}/`;
  if (!file.startsWith(prefix)) return false;
  const rest = file.slice(prefix.length);
  // No `..` segments and no absolute path: the file must stay in the directory.
  return rest.length > 0 && !rest.split('/').includes('..') && !path.isAbsolute(file);
}

export interface SpecTestWriter {
  write(input: { readonly files: readonly SpecTestFile[] }): void;
}

/**
 * Writes authored spec tests under a target directory (the run directory).
 *
 * The target is the run directory, not the repository: the files are evidence to
 * review, and copying them into the working tree is a separate, explicit step.
 * That way a malformed reply cannot pollute the repo.
 */
export function createFileSpecTestWriter(targetDir: string): SpecTestWriter {
  return {
    write({ files }) {
      for (const entry of files) {
        const resolved = path.resolve(targetDir, entry.file);
        const root = path.resolve(targetDir);
        // Defence in depth: the parser already refuses escapes, and this refuses
        // them again so a caller that builds files by hand cannot write outside.
        if (resolved !== root && !resolved.startsWith(`${root}${path.sep}`)) {
          throw new Error(`refusing to write ${entry.file}: outside ${targetDir}`);
        }
        mkdirSync(path.dirname(resolved), { recursive: true });
        writeFileSync(resolved, entry.content);
      }
    },
  };
}
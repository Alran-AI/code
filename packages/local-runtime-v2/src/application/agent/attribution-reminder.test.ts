import { describe, expect, it } from 'vitest';

import { createAttributionReminder } from './attribution-reminder.js';

const werk = { model: { provider: 'alran', model_id: 'Alran-Werk' } };
const opus = { model: { provider: 'alran', model_id: 'anthropic/claude-opus-5.5' } };

describe('attribution reminder', () => {
  it('goes out on the first turn of a session, with the model, and only then', () => {
    const reminder = createAttributionReminder({ readConfig: () => undefined });
    const first = reminder.build({ sessionId: 's1', agentConfig: werk });
    expect(first).toContain('Co-Authored-By: Alran Code using Werk 1.1 <noreply@alran.dev>');
    expect(first).toContain('Generated by [Alran Code](https://alran.dev)');
    expect(reminder.build({ sessionId: 's1', agentConfig: werk, sessionIdInContext: true })).toBe('');
    expect(reminder.build({ sessionId: 's1', agentConfig: werk, sessionIdInContext: true })).toBe('');
  });

  it('comes again after a compaction dropped it, and when the turn runs on another model', () => {
    const reminder = createAttributionReminder({ readConfig: () => undefined });
    reminder.build({ sessionId: 's1', agentConfig: werk });
    // A compaction: the session id is no longer in the model-visible history.
    expect(reminder.build({ sessionId: 's1', agentConfig: werk })).toContain('Werk 1.1');
    expect(reminder.build({ sessionId: 's1', agentConfig: werk, sessionIdInContext: true })).toBe('');
    // The model changed: the commit line names it, so the old text is stale.
    expect(reminder.build({ sessionId: 's1', agentConfig: opus, sessionIdInContext: true })).toContain('using Opus 5.5');
    expect(reminder.build({ sessionId: 's1', agentConfig: opus, sessionIdInContext: true })).toBe('');
  });

  it('keeps sessions apart', () => {
    const reminder = createAttributionReminder({ readConfig: () => undefined });
    expect(reminder.build({ sessionId: 'a', agentConfig: werk })).not.toBe('');
    expect(reminder.build({ sessionId: 'b', agentConfig: opus })).toContain('Opus 5.5');
    expect(reminder.build({ sessionId: 'a', agentConfig: werk, sessionIdInContext: true })).toBe('');
  });

  it('follows the config as it is now: off says nothing, back on says it again', () => {
    let attribution: { commits: boolean; pullRequests: boolean } = { commits: false, pullRequests: false };
    const reminder = createAttributionReminder({ readConfig: () => ({ attribution }) });
    expect(reminder.build({ sessionId: 's', agentConfig: werk })).toBe('');
    attribution = { commits: true, pullRequests: false };
    const text = reminder.build({ sessionId: 's', agentConfig: werk, sessionIdInContext: true });
    expect(text).toContain('Co-Authored-By');
    expect(text).not.toContain('Generated by');
  });

  it('copes with a turn that has no model', () => {
    const reminder = createAttributionReminder({ readConfig: () => undefined });
    expect(reminder.build({ sessionId: 's', agentConfig: {} })).toContain('Co-Authored-By: Alran Code <noreply@alran.dev>');
  });
});

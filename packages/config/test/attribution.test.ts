import { describe, expect, it } from 'vitest';

import { resolveConfigFromRaw } from '../src/config.js';
import {
  ATTRIBUTION_DEFAULTS,
  PULL_REQUEST_ATTRIBUTION,
  attributionModelLabel,
  buildAttributionReminder,
  commitTrailer,
  commitTrailerFor,
  parseAttributionConfig,
} from '../src/attribution.js';

describe('attribution config', () => {
  it('is on for commits and pull requests when the config says nothing', () => {
    expect(resolveConfigFromRaw({}, '/tmp/attribution-config').attribution).toEqual({ commits: true, pullRequests: true });
    expect(ATTRIBUTION_DEFAULTS).toEqual({ commits: true, pullRequests: true });
  });

  it('is switched off per line by an explicit false, and nothing else counts', () => {
    expect(parseAttributionConfig({ attribution: { commits: false } })).toEqual({ commits: false, pullRequests: true });
    expect(parseAttributionConfig({ attribution: { pullRequests: false } })).toEqual({ commits: true, pullRequests: false });
    expect(parseAttributionConfig({ attribution: { commits: false, pullRequests: false } })).toEqual({ commits: false, pullRequests: false });
    for (const value of [undefined, null, [], 'off', 0, { commits: 'false', pullRequests: 0 }]) {
      expect(parseAttributionConfig({ attribution: value })).toEqual({ commits: true, pullRequests: true });
    }
  });
});

describe('the model as the trailer names it', () => {
  it.each([
    ['Alran-Werk', 'Werk 1.1'],
    ['ottili/werk-1.1', 'Werk 1.1'],
    ['werk-2', 'Werk 2'],
    ['anthropic/claude-sonnet-5.5', 'Sonnet 5.5'],
    ['anthropic/claude-opus-5.5', 'Opus 5.5'],
    ['claude-opus-5-5', 'Opus 5.5'],
    ['sonnet-5.5', 'Sonnet 5.5'],
    ['gpt-5.1', 'gpt-5.1'],
    ['acme/some-model-v2', 'some-model-v2'],
    ['', ''],
  ])('%s -> %s', (id, label) => {
    expect(attributionModelLabel(id)).toBe(label);
  });

  it('never lets an id put anything but a plain name into a commit message', () => {
    for (const hostile of ['x/evil\n<script>alert(1)', 'x/a\r\nSigned-off-by: someone', 'x/"quoted"; rm -rf $HOME', 'x/\u0000\u001b[31mred']) {
      const label = attributionModelLabel(hostile);
      expect(label).toMatch(/^[\p{L}\p{N} ._+()/-]*$/u);
      expect(label).not.toMatch(/[\n\r<>"$;]/u);
    }
    expect(attributionModelLabel('x/a\r\nSigned-off-by: someone')).toBe('a Signed-off-by someone');
    expect(attributionModelLabel(`m/${'a'.repeat(500)}`)).toHaveLength(64);
    expect(attributionModelLabel(undefined)).toBe('');
  });
});

describe('the commit trailer', () => {
  it('has the documented shape', () => {
    expect(commitTrailer('Werk 1.1')).toBe('Co-Authored-By: Alran Code using Werk 1.1 <noreply@alran.dev>');
    expect(commitTrailer('Sonnet 5.5')).toBe('Co-Authored-By: Alran Code using Sonnet 5.5 <noreply@alran.dev>');
    expect(commitTrailer('Opus 5.5')).toBe('Co-Authored-By: Alran Code using Opus 5.5 <noreply@alran.dev>');
    expect(commitTrailer()).toBe('Co-Authored-By: Alran Code <noreply@alran.dev>');
  });

  it('follows the turn model and the user setting', () => {
    expect(commitTrailerFor({ model_id: 'Alran-Werk' }, undefined)).toBe('Co-Authored-By: Alran Code using Werk 1.1 <noreply@alran.dev>');
    expect(commitTrailerFor({ model_id: 'anthropic/claude-opus-5.5' }, { commits: true })).toBe(
      'Co-Authored-By: Alran Code using Opus 5.5 <noreply@alran.dev>',
    );
    expect(commitTrailerFor(undefined, undefined)).toBe('Co-Authored-By: Alran Code <noreply@alran.dev>');
    expect(commitTrailerFor({ model_id: 'Alran-Werk' }, { commits: false })).toBeUndefined();
    expect(/[\u0000-\u001f]/u.test(commitTrailerFor({ model_id: 'a\nb\r\tc' }, undefined) ?? '')).toBe(false);
  });
});

describe('the attribution reminder', () => {
  it('asks for both lines, with the model', () => {
    expect(buildAttributionReminder({ model: { model_id: 'Alran-Werk' }, config: undefined })).toBe(
      [
        "Attribution for git commits and pull requests you create from here on (replaces any earlier attribution guidance, including an earlier copy of this reminder; the user's own instructions about these lines, such as AGENTS.md or memory rules, take precedence over this reminder, but do not add attribution lines this reminder leaves out):",
        '',
        '- End git commit messages with:',
        'Co-Authored-By: Alran Code using Werk 1.1 <noreply@alran.dev>',
        '- End pull request descriptions with:',
        'Generated by [Alran Code](https://alran.dev)',
      ].join('\n'),
    );
    expect(PULL_REQUEST_ATTRIBUTION).toBe('Generated by [Alran Code](https://alran.dev)');
  });

  it('leaves out what the user switched off, and is absent when both are', () => {
    const model = { model_id: 'anthropic/claude-sonnet-5.5' };
    const commitsOnly = buildAttributionReminder({ model, config: { pullRequests: false } });
    expect(commitsOnly).toContain('Co-Authored-By: Alran Code using Sonnet 5.5 <noreply@alran.dev>');
    expect(commitsOnly).not.toContain('Generated by');
    const pullRequestsOnly = buildAttributionReminder({ model, config: { commits: false } });
    expect(pullRequestsOnly).toContain('Generated by [Alran Code](https://alran.dev)');
    expect(pullRequestsOnly).not.toContain('Co-Authored-By');
    expect(buildAttributionReminder({ model, config: { commits: false, pullRequests: false } })).toBeUndefined();
  });
});

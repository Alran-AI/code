/**
 * Loop protection for the CI Fixer.
 *
 * A fix commit must never trigger another fix run. Two mechanisms enforce that:
 * the generated workflow skips any head commit whose message carries the
 * `[alran-ci-fix]` marker, and the attempt counter spans the whole commit chain
 * so `max_attempts` bounds total effort per failure, not per run.
 */

import { CI_FIX_MARKER } from './config.js';

export { CI_FIX_MARKER };

/** True when the commit message was produced by Alran CI Fix. */
export function isCiFixCommitMessage(message: string): boolean {
  return message.includes(CI_FIX_MARKER);
}

/**
 * Counts the Alran CI fix commits in a commit chain, newest first. Each fix
 * attempt appends one marker commit, so the count is the number of attempts
 * already spent on this failure. The budget applies across the whole chain,
 * not just the head, so a later feature commit cannot reset it.
 */
export function countCiFixAttempts(commitChainNewestFirst: readonly string[]): number {
  let count = 0;
  for (const message of commitChainNewestFirst) {
    if (isCiFixCommitMessage(message)) count += 1;
  }
  return count;
}

export interface LoopGuardDecision {
  readonly run: boolean;
  readonly reason?: string;
}

export interface LoopGuardInput {
  /** Message of the head commit of the checked-out ref. */
  readonly headCommitMessage: string;
  /** Commit messages of the branch chain, newest first. */
  readonly commitChain: readonly string[];
  readonly maxAttempts: number;
}

/**
 * Decides whether a fix run may start. Returns `run: false` when the head
 * commit is itself a fix commit (self-trigger loop) or when the chain already
 * spent the configured number of attempts.
 */
export function evaluateLoopGuard(input: LoopGuardInput): LoopGuardDecision {
  if (isCiFixCommitMessage(input.headCommitMessage)) {
    return {
      run: false,
      reason: `head commit carries ${CI_FIX_MARKER}; a fix commit never re-triggers a fix`,
    };
  }
  const attempts = countCiFixAttempts(input.commitChain);
  if (attempts >= input.maxAttempts) {
    return {
      run: false,
      reason: `attempt budget exhausted: ${attempts} of ${input.maxAttempts} fix attempts already spent on this chain`,
    };
  }
  return { run: true };
}

/**
 * Builds the fix commit message. The subject follows Conventional Commits; the
 * body carries the marker that the workflow and the loop guard look for.
 */
export function buildCiFixCommitMessage(summary: string): { subject: string; body: string } {
  const subject = `fix(ci): ${summary}`;
  const body = [
    `${CI_FIX_MARKER} automated fix for a failing CI command`,
    '',
    'Generated by Alran Code CI Fixer. The failing command was re-run locally',
    'and only passed changes were committed. Reply to the pull request if the',
    'fix needs adjustments.',
  ].join('\n');
  return { subject, body };
}

/**
 * Generator for the installed GitHub Action workflow.
 *
 * The workflow is the only GitHub-specific artifact of Phase 1. It triggers on
 * `workflow_run` for the monitored workflows, filters failures, refuses forks at
 * the workflow level, checks out the failing head commit from the same
 * repository, and hands over to `alran ci fix --workflow-run`, which runs the
 * GitHub-agnostic core from @alran/ci-fix.
 *
 * Permissions are minimal on purpose: contents write (commit the fix),
 * pull-requests write (the summary comment), actions read (inspect the failed
 * run). Nothing else.
 */

export interface CiFixWorkflowInput {
  readonly monitoredWorkflows: readonly string[];
  /** Command the workflow runs; defaults to `alran ci fix --workflow-run`. */
  readonly fixCommand?: string;
}

const DEFAULT_FIX_COMMAND = 'alran ci fix --workflow-run';

export function renderCiFixWorkflow(input: CiFixWorkflowInput): string {
  const workflows = input.monitoredWorkflows.length > 0 ? [...input.monitoredWorkflows] : ['CI'];
  const fixCommand = input.fixCommand?.trim() || DEFAULT_FIX_COMMAND;
  const workflowLines = workflows.map((name) => `      - ${JSON.stringify(name)}`).join('\n');

  return `# Generated by \`alran ci init\`. Re-run \`alran ci init\` to change this file.
name: Alran CI Fix
on:
  workflow_run:
    workflows:
${workflowLines}
    types:
      - completed
permissions:
  contents: write
  pull-requests: write
  actions: read
jobs:
  alran-ci-fix:
    # Forks are never fixed: the failing run must come from this repository.
    if: >-
      github.event.workflow_run.conclusion == 'failure' &&
      github.event.workflow_run.head_repository.full_name == github.repository
    runs-on: ubuntu-latest
    steps:
      - name: Check out the failing head commit
        uses: actions/checkout@v4
        with:
          ref: \${{ github.event.workflow_run.head_sha }}
      - name: Set up Node.js
        uses: actions/setup-node@v4
        with:
          node-version: 22
      - name: Install Alran Code
        run: npm install -g alran
      - name: Reproduce, fix, verify and report
        env:
          ALRAN_API_KEY: \${{ secrets.ALRAN_API_KEY }}
          ALRAN_CI_PUSH_TOKEN: \${{ secrets.ALRAN_CI_PUSH_TOKEN }}
          ALRAN_CI_RUN_ID: \${{ github.event.workflow_run.id }}
          GITHUB_TOKEN: \${{ secrets.GITHUB_TOKEN }}
        run: ${fixCommand}
`;
}
